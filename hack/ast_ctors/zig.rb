# Constructors for the Zig binding.
#
# `zig/src/ast/` is hand-written — `base.zig dto.zig expr.zig module.zig
# stmt.zig types.zig`, about 2400 lines of typed Zig structs beside a JSON
# walker — and there is no `AstBuild.kt` counterpart. There does not need to
# be one: in Zig a struct *is* its constructor and the struct literal is the
# whole of the call syntax, so a node's parameters are its declared fields in
# declaration order. The same argument `check_python` makes about a
# dataclass's generated `__init__` and `check_go` makes about a keyed struct
# literal applies unchanged, and `zig/src/ast.zig:161` builds one the way a
# caller outside the package would — `ConfigEntry.dump(a, .{ .key = null,
# .value = null, .operation = "Union" })`.
#
# Zig is *not* Go's answer, and that difference is the whole finding. Go
# fills an omitted field with the zero value; Zig has no zero fill. A struct
# literal must name every field the struct declares unless that field carries
# a default value (`name: T = …`), so the three shapes a Zig caller meets are:
#
#   * `?*ExprNode` — an optional child, and still required. Building a
#     `SchemaStmt` spells `.doc = null`, `.name = null`, `.parent_name = null`
#     and nine more; none of its twelve fields has a default.
#   * `std.ArrayList(*StmtNode)` — a list, and still required. `.body = .empty`
#     is ceremony at every level of the tree.
#   * `bool = false` / `?i64 = null` — a declared default, and omittable.
#
# Only three declarations carry a default anywhere (`base.zig:36`'s `Pos`,
# `base.zig:49`'s `Node`, and `ConfigEntry.is_shorthand` at `dto.zig:95`), so
# `defaulted` is empty almost everywhere. That is Zig's answer rather than a
# generous reading of one, and it is why rule 1 fires on most structs with a
# `Vec` field. It is the finding Swift's collector reports, one step further:
# Swift's caller at least writes `[]` for a required list, whereas a Zig caller
# has to name the field at all. `Pos` and `Node` are the only two places the
# language lets a caller leave a field out, and both are in `NOT_NODES`.
#
# Four shapes in the source decide what counts, and not one of them is a
# function: there is no `pub fn init(…)` anywhere in `zig/src/ast/`
# (`kcl.zig:74`'s `Options.init` is the exec API's options, not an AST node),
# so every constructor here is a declaration.
#
#   * `pub const X = struct { … }` — the payload structs.
#   * `pub const X = union(enum) { … }` — `Stmt`, `Expr`, `Type` and
#     `MemberOrIndex`. A variant is how a caller builds one (`.{ .schema =
#     schemaStmt }`), so the variants are the parameters. None of the four
#     names a struct in `ast.rs` — they are Rust's `pub enum`s — so all four
#     arrive in `unmapped`, which is what they are.
#   * `pub fn X(comptime T: type) type { return struct { … }; }` — the two
#     generic wrappers, `Node(T)` at `base.zig:46` and `RawUnknown(T)` at
#     `base.zig:274`, whose fields sit at eight spaces rather than four.
#   * `pub const X = <module>.<Y>;` — a re-export or an alias, not a
#     declaration: `dto.zig:75`, `dto.zig:83` and `dto.zig:119`'s
#     `KeyValuePair` are three. The pattern requires `struct {` on the
#     right-hand side, so an alias is dropped rather than returned under a
#     name `ast.rs` does not declare, for the reason `check_go` gives about
#     `type Decorator = CallExpr`.
#
# `zig/src/ast.zig` re-exports the package and contributes nothing — every
# line of it is a `pub const … = @import(…)` — and `zig/src/proto/` is protoc
# output, skipped on its `// Code generated by protoc-gen-zig` header rather
# than on its path. That is not tidiness: the generated tree declares its own
# `FunctionType` (`api.pb.zig:7209`, a protobuf message of name and type
# strings) and `types.zig:115` declares the `FunctionType` that `ast.rs:1870`
# makes a node type, so without the header check the two would be one name
# reaching one struct and the protobuf message would read as coverage. The
# tree's `ExternalPkg` and `Argument` are the same trap for the two structs in
# `NOT_ON_THE_WIRE`. `*_test.zig` is the test's scaffolding, as `*_test.go` is
# for Go; none of the three declares a container today, so the skip is the
# belt to the braces the header check already is.
#
# Three things this collector does not see, stated here rather than left for a
# reader to assume:
#
#   * `IntLiteralType` (`ast.rs:1909` — `pub value: i64` plus `pub suffix`)
#     has no Zig struct. `types.zig:195` keeps a literal type as
#     `value: std.json.Value`, the raw `{"type":"Int","value":3}` object, so
#     the payload behind `LiteralType::Int(IntLiteralType)` (`ast.rs:1903`) is
#     never given a type a caller could spell. It is the one node type no
#     constructor here reaches, and unlike Kotlin's `literalIntType` there is
#     no `WRAPPED_PAYLOADS` entry to declare: no function returns the wrapper
#     either, because a Zig caller writes the union literal inline.
#   * Two field names are dodged around a Zig keyword — `test` is a builtin
#     and `orelse` a keyword, so the structs spell them `test_` and `orelse_`
#     (`expr.zig:739`, `expr.zig:117`, `expr.zig:224`, `expr.zig:281`,
#     `expr.zig:376`, `stmt.zig:317`, `stmt.zig:367`) — and
#     `Program.modules` is `ast.rs`'s `pkgs` (`ast.rs:388`) under a name a
#     reader can follow. Each is a `PARAM_ALIASES` entry waiting on a
#     justification; none is added here, so `compare` reports them.
#   * Every `parse` / `dump` pair takes a document rather than a node's
#     fields, so none is a constructor — they are the wire walker, and a
#     method is `pub fn`, never `pub const … = struct {`.

# The Zig names that mean something `ast.rs` spells differently, each with the
# declaration it is checked against. A rename is a claim a reviewer can look
# up, so none is guessed in a regex. `ast.rs`'s own `Program` (line 435) is
# the resolution index — it derives only `Debug, Clone, Default`, holds
# `Vec<String>` where the serialised form holds `Vec<Module>`, and is never
# serialised; it is in `NOT_ON_THE_WIRE`.
ZIG_AST_RS_NAMES = {
  "SubscriptExpr" => "Subscript",             # ast.rs:1302
  "CompareExpr" => "Compare",                 # ast.rs:1385
  "ListCompExpr" => "ListComp",               # ast.rs:1137
  "DictCompExpr" => "DictComp",               # ast.rs:1157
  "NumberLitExpr" => "NumberLit",             # ast.rs:1476
  "StringLitExpr" => "StringLit",             # ast.rs:1500
  "NameConstantLitExpr" => "NameConstantLit", # ast.rs:1566
  "JoinedStringExpr" => "JoinedString",       # ast.rs:1572
  "FormattedValueExpr" => "FormattedValue",   # ast.rs:1580
  "Program" => "SerializeProgram"             # ast.rs:386
}.freeze

# Zig source with its comments and its string literals blanked out, newline
# for newline, so that what is left is only code.
#
# Zig has one comment form and no block comment, so `//` to end of line is the
# whole job — but a scanner rather than a `sub`, because a `//` inside a
# string is code and dropping the rest of the line with it silently loses a
# declaration. The doc comments are where that matters most here: every one
# of `zig/src/ast/` opens with a `//!` banner quoting `ast.rs`, and
# `expr.zig:571` writes the `{"type": "Int"|"Float", "value": …}` shape a
# literal carries. Blanking the strings rather than preserving them also
# makes the brace matcher below safe, since a `{` inside a string is not a
# container. Zig's `\\` line continuation and `'c'` character literals are
# not used in this package and are not handled.
def zig_code(src)
  out = +""
  i = 0
  n = src.length

  while i < n
    c = src[i]

    if c == "/" && src[i + 1] == "/"
      i += 2
      i += 1 while i < n && src[i] != "\n"
      next
    end

    if c == "@" && src[i + 1] == '"'
      # `@"if"` is an identifier, not a literal: it is how a Zig keyword is
      # spelled as a field or a union-variant name, and it is the one string
      # form that can appear where this walk reads a name. Copying it through
      # keeps `Stmt`'s `@"if": IfStmt,` readable; every other `"…"` is data.
      j = i + 2
      j += 1 while j < n && src[j] != '"' && src[j] != "\n"
      j += 1 if j < n && src[j] == '"'
      out << src[i...j]
      i = j
      next
    end

    if c == '"'
      i += 1
      # Backslash first: an escaped `\"` must not close the literal. The
      # newline guard is what keeps a line continuation from swallowing the
      # next line, and a literal that ran to one was never closed at all.
      while i < n && src[i] != "\n" && src[i] != '"'
        i += (src[i] == "\\" && src[i + 1] && src[i + 1] != "\n") ? 2 : 1
      end
      i += 1 if i < n && src[i] == '"'
      # The blanked literal takes its newline with it unless this puts it
      # back: losing one would splice two declarations onto one line and turn
      # a readable one into something the raise below rejects.
      if i < n && src[i] == "\n"
        out << "\n"
        i += 1
      end
      next
    end

    out << c
    i += 1
  end

  out
end

# The text between the `{` at `open` and the `}` that closes it, or nil.
#
# The count starts at one — the brace the caller found — so that the first
# iteration cannot report an empty body for a scan that starts anywhere other
# than on a `{`.
def zig_body(code, open)
  depth = 1
  i = open + 1
  n = code.length

  while i < n
    depth += 1 if code[i] == "{"
    depth -= 1 if code[i] == "}"
    return code[(open + 1)...i] if depth.zero?

    i += 1
  end
  nil
end

# The declared fields of a container body, as `[params, defaulted]`.
#
# Fields stop at the first declaration, which is the rule `check_python`
# applies at the first `def`: a method body is a wall of `.field = value`
# initializers and is not a field list. The indent is read off the first line
# rather than passed in, so the same walk reads a top-level struct's
# four-space fields and a generic wrapper's eight-space ones.
#
# A field is required unless it declares a default, and `?T` is not a default:
# `.doc = null` is still something the caller has to write. The `=` that
# decides it is looked for at bracket depth 0, because `std.ArrayList([]const
# u8)` and a `= .empty` default both carry brackets that mean nothing here.
def zig_members(body)
  params = []
  defaulted = []
  indent = nil

  body.each_line do |raw|
    text = raw.strip
    next if text.empty?

    indent ||= raw[/\A */].length
    # Deeper than the field block means a method body, not a declaration.
    next if raw[/\A */].length > indent

    # `pub const Payload = T;` sits inside `Node(T)` and is a declaration,
    # not a field; `pub const Payload` has no colon and would otherwise be
    # the one line this walk could not read.
    break if text.match?(/\A(?:pub\s+)?(?:fn|const|var|usingnamespace|test)\b/)

    # A field is `name: Type` and a union variant is the same spelling — the
    # variant name is the label the caller builds the union with. `@"if"` is
    # how `Stmt` spells a variant whose name is a Zig keyword.
    m = text.match(/\A((?:@)?"[^"]+"|[A-Za-z_][A-Za-z0-9_]*)\s*:\s*(.*)\z/)
    raise "cannot read this line of a Zig container as a field: #{text}" if m.nil?

    name = m[1].delete("@").delete('"')
    depth = 0
    has_default = false
    m[2].each_char do |ch|
      case ch
      when "(", "[", "{" then depth += 1
      when ")", "]", "}" then depth -= 1
      when "="
        if depth.zero?
          has_default = true
          break
        end
      end
    end

    params << name
    defaulted << name if has_default
  end

  [params, defaulted]
end

def check_zig(path)
  files = File.directory?(path) ? Dir[File.join(path, "**", "*.zig")].sort : [path]

  ctors = []
  seen = {}
  decls = 0

  emit = lambda do |name, params, defaulted|
    # Two declarations of one name do not compile, so a repeat can only be the
    # same type reached twice, and recording it twice would inflate the count
    # the report prints.
    ast_rs = ZIG_AST_RS_NAMES.fetch(name, name)
    next if seen.key?(ast_rs)

    seen[ast_rs] = true
    # Separate objects because `compare` subtracts one from the other.
    ctors << [ast_rs, params, defaulted]
  end

  files.each do |file|
    src = File.read(file)
    next if src.start_with?("// Code generated by")
    next if File.basename(file).end_with?("_test.zig")

    code = zig_code(src)

    # A payload struct or a tagged union. The declaration consumes the whole
    # header so the brace the body starts at is the one the pattern matched.
    code.scan(/^pub const ((?:@)?"[^"]+"|[A-Za-z_][A-Za-z0-9_]*) = (?:struct|union\(enum\)) \{/) do
      decls += 1
      name = Regexp.last_match[1].delete("@").delete('"')
      open = Regexp.last_match.end(0) - 1

      body = zig_body(code, open)
      raise "#{file}: `#{name}` has no closing brace" if body.nil?

      params, defaulted = zig_members(body)
      emit.call(name, params, defaulted)
    end

    # The generic wrappers: `pub fn Node(comptime T: type) type { return
    # struct { … }; }`. A comptime parameter makes the type a constructor, and
    # a caller reaches it exactly as it reaches a named struct — the fields
    # are named in the literal either way.
    code.scan(/^pub fn ([A-Za-z_][A-Za-z0-9_]*)\(comptime[^)]*\) type \{/) do
      name = Regexp.last_match[1]
      outer = zig_body(code, Regexp.last_match.end(0) - 1)
      next if outer.nil?

      inner = outer.match(/return struct \{/)
      next if inner.nil?

      decls += 1
      body = zig_body(outer, inner.end(0) - 1)
      raise "#{file}: the type `#{name}` returns a struct with no closing brace" if body.nil?

      params, defaulted = zig_members(body)
      emit.call(name, params, defaulted)
    end
  end

  # A collector that stopped matching reports success, which is worse than
  # useless. No container declaration at all is the shape that takes, so it is
  # raised rather than counted.
  raise "no Zig AST declarations found under #{path} - the parse stopped matching" if decls.zero?

  ctors
end