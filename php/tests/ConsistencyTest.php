/**
 * The cross-language consistency runner: executes the hermetic cases from
 * tests/consistency/cases.json (generated by tests/consistency/generate_cases.py)
 * and asserts the same pinned expectations as the lua/python/go/java/dotnet
 * runners. The manifest spells every proto3 field out, but the unset ones
 * carry their proto defaults, so only the fields a case actually drives are
 * compared — and exactly those, sorted, the way the lua runner does it.
 */
final class ConsistencyTest extends TestCase
{
    private static ?ServiceClient $client = null;
    /** @var array<string, bool>|null */
    private static ?array $methods = null;

    public static function setUpBeforeClass(): void
    {
        self::$client = new ServiceClient();
    }

    private static function client(): ServiceClient
    {
        return self::$client ??= new ServiceClient();
    }

    /** @return array<string, mixed> */
    private static function manifest(): array
    {
        static $manifest = null;
        $manifest ??= json_decode(
            (string) file_get_contents(dirname(__DIR__, 2) . '/tests/consistency/cases.json'),
            true,
            512,
            JSON_THROW_ON_ERROR
        );

        return $manifest;
    }

    /** @return array<string, mixed> */
    private static function findCase(string $name): array
    {
        foreach (self::manifest()['cases'] as $case) {
            if ($case['name'] === $name) {
                return $case;
            }
        }
        throw new \RuntimeException("consistency case not found in manifest: {$name}");
    }

    /**
     * The RPC surface of the core this binding is linked against, as a set,
     * resolved once per run. Cores that predate `BuiltinService.ListMethod`
     * answer with an empty list or raise; either way `new_core` cases are
     * skipped rather than failed.
     *
     * @return array<string, bool>
     */
    private static function methods(): array
    {
        if (self::$methods !== null) {
            return self::$methods;
        }
        $set = [];
        try {
            $result = self::client()->listMethod();
            foreach ($result->getMethodNameList() as $name) {
                $set[$name] = true;
            }
        } catch (KclException) {
            // old core: every new_core case below skips
        }
        self::$methods = $set;

        return $set;
    }

    /**
     * Build the request message for one case and dispatch it, the same
     * reduction every runner makes: the manifest's snake_case args apply
     * directly through the protobuf-JSON codec, with repo-relative paths
     * resolved against the repository root.
     */
    private static function runCase(array $case): Message
    {
        $args = $case['args'];
        $rpc = $case['rpc'];
        $root = dirname(__DIR__, 2);

        $resolve = static function (&$value) use (&$resolve, $root): void {
            if (is_string($value) && str_ends_with($value, '.k') && !str_starts_with($value, '/')
                && is_file($root . '/' . $value)) {
                $value = $root . '/' . $value;
                return;
            }
            if (is_array($value)) {
                foreach ($value as &$item) {
                    $resolve($item);
                }
            }
        };
        $resolve($args);

        return self::client()->{$rpc === 'KclService.Ping' ? 'ping' : self::methodName($rpc)}($args);
    }

    private static function methodName(string $rpc): string
    {
        $short = substr($rpc, strlen('KclService.'));

        return lcfirst($short);
    }

    /** @return mixed */
    private static function fieldOf(Message $result, string $key): mixed
    {
        $studly = str_replace(' ', '', ucwords(str_replace('_', ' ', $key)));
        $getter = 'get' . $studly;
        if (method_exists($result, $getter)) {
            $value = $result->{$getter}();

            return $value instanceof \Google\Protobuf\Internal\RepeatedField
                ? iterator_to_array($value)
                : $value;
        }

        $json = json_decode($result->serializeToJsonString(), true);

        return $json[$key] ?? '';
    }

    private function assertCase(string $name): void
    {
        $case = self::findCase($name);
        $expect = $case['expect'];
        ksort($expect);
        self::assertNotEmpty($expect, "consistency case `{$name}` pins no fields");

        if (($case['new_core'] ?? false) && !isset(self::methods()[$case['rpc']])) {
            $this->markTestSkipped("core does not list {$case['rpc']} (old core)");
        }

        $result = self::runCase($case);
        foreach ($expect as $key => $expected) {
            $actual = self::fieldOf($result, $key);
            $this->assertEquals(
                $expected,
                $actual,
                "consistency case `{$name}` field `{$key}` mismatch"
            );
        }
    }

    public function testManifestCoversThirteenCases(): void
    {
        $this->assertCount(13, self::manifest()['cases']);
    }

    public function testPing(): void
    {
        $this->assertCase('ping');
    }

    public function testExecProgramBasic(): void
    {
        $this->assertCase('exec_program_basic');
    }

    public function testExecProgramOverrides(): void
    {
        $this->assertCase('exec_program_overrides');
    }

    public function testFormatCode(): void
    {
        $this->assertCase('format_code');
    }

    public function testValidateCodeOk(): void
    {
        $this->assertCase('validate_code_ok');
    }

    public function testValidateCodeInvalid(): void
    {
        $this->assertCase('validate_code_invalid');
    }

    public function testGenerateKclJson(): void
    {
        $this->assertCase('generate_kcl_json');
    }

    public function testGenerateKclYaml(): void
    {
        $this->assertCase('generate_kcl_yaml');
    }

    public function testGenerateToml(): void
    {
        $this->assertCase('generate_toml');
    }

    public function testFormatTestReport(): void
    {
        $this->assertCase('format_test_report');
    }

    public function testGenerateOpenAPIV3(): void
    {
        $this->assertCase('generate_openapi_v3');
    }

    public function testGenerateProto(): void
    {
        $this->assertCase('generate_proto');
    }

    public function testGenerateDocMd(): void
    {
        $this->assertCase('generate_doc_md');
    }
}
