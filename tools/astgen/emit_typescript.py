    def exports(self, module: str) -> List[str]:
        """The names `index.ts` re-exports from one module.

        Derived from the same rule the file itself is emitted with -- a class
        contributes its interface and, when it has one, its loader -- so a
        variant added to `ast.rs` is re-exported the day it is declared. The
        entries `index.ts` adds by hand are the ones that are not a class: the
        wrapper type the position lives in, the hand-written helpers
        (`BASE_HELPERS`), and the two JSON-string entry points.
        """
        m = self.m
        out: Set[str] = set()
        if module == "_base":
            out |= {"Pos", "Node", "MaybeNode"} | set(BASE_HELPERS)
        for cm in m.classes.values():
            if cm.module == module and cm.kind not in ("variant", "compact_value", "node_wrapper"):
                out.add(cm.name)
                if self._has_loader(cm):
                    out.add(self.loader_name(cm.rust_name))
            if cm.module == module and cm.kind == KIND_COMPACT_NODE:
                out.add(cm.name)
                out.add(self.loader_name(cm.rust_name))
        for cm in m.variants.values():
            if cm.module != module:
                continue
            out.add(cm.name)
            if self._has_loader(cm):
                out.add(self.loader_name(cm.rust_name))
        if module == "_expr":
            out.add("exprFromWire")
        if module == "_stmt":
            out.add("stmtFromWire")
        if module == "_types":
            out |= {"Type", "UnknownType", "typeFromWire"}
        if module == "_module":
            out |= {"parseModule", "parseProgram", "moduleFromWire"}
        return sorted(n for n in out if not n.startswith("_"))

    def _emit_index(self) -> str:
        text = HEADER.format(sha=self.m.source_sha[:16])
        text += f"{narrative.TS_MODULE_DOCS['index'].rstrip()}\n\n"
        for module in MODULES:
            names = self.exports(module)
            if not names:
                continue
            text += f"export {{ {', '.join(names)} }} from './{module}';\n"
        return text


