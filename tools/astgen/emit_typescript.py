def loader_name(payload: str) -> str:
    return naming.camel_case(naming.payload_word(payload)) + "FromWire"


def _payload_note(tag: str, payload: str) -> str:
    if payload == "String":
        return f"the `{tag}` payload is a bare `NodeRef<String>`, not an expression"
    return f"the `{tag}` payload is a `NodeRef<{payload}>`"


def _jsdoc(text: str) -> List[str]:
    """A JSDoc block. Multi-line prose is re-indented so the block reads as one."""
    lines = text.strip("\n").split("\n")
    if len(lines) == 1:
        return [f"/** {lines[0]} */"]
    out = ["/**"]
    out += [(" * " + line).rstrip() for line in lines]
    out.append(" */")
    return out


def _import(module: str, names: List[str], type_only: bool) -> List[str]:
    """One import clause, wrapped rather than run onto a 200-character line.

    `_expr.ts` needs nine decoders from `_dto`, and a single line listing all of
    them is the difference between a diff that shows the name that changed and
    one that shows nothing changed at all.
    """
    if not names:
        return []
    head = "import type {" if type_only else "import {"
    tail = f" }} from './{module}';"
    one = head + " " + ", ".join(names) + tail
    if len(one) <= 96:
        return [one]
    return [head, *(f"  {name}," for name in names), "} from " + f"'./{module}';"]


def _inner_doc(text: str, indent: str) -> List[str]:
    """The body lines of a JSDoc block, given without its `/**` and ` */`.

    `narrative.TS_FIELD_NOTES` stores the inside of a field comment rather than
    the whole block, so a field note can be two lines long without every one of
    them repeating the delimiters.
    """
    return [(indent + line.lstrip()).rstrip() for line in text.strip("\n").split("\n")]
