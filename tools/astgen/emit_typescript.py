    # files
    # ------------------------------------------------------------------

    def emit(self, name: str) -> str:
        self._imports: Dict[str, Dict[str, Set[str]]] = {}
        if name == "index.ts":
            return self._emit_index()
        module = name[:-3]
        if module not in MODULES:
            raise EmitError(f"unknown generated file {name}")
        body = self._emit_body(module, name)
        text = HEADER.format(sha=self.m.source_sha[:16])
        text += f"\n{narrative.TS_MODULE_DOCS[module].rstrip()}\n"
        for line in self._import_lines(module):
            text += line + "\n"
        return text + "\n" + "\n".join(body).rstrip("\n") + "\n"

    def _import_lines(self, module: str) -> List[str]:
        out: List[str] = []
        buckets = self._imports.get(module, {})
        for mod in sorted(k for k in buckets if not k.startswith(TYPE_BUCKET)):
            out.extend(_import(mod, sorted(buckets[mod]), type_only=False))
        for key in sorted(k for k in buckets if k.startswith(TYPE_BUCKET)):
            out.extend(
                _import(key[len(TYPE_BUCKET) :], sorted(buckets[key]), type_only=True)
            )
        return out

    def _emit_body(self, module: str, name: str) -> List[str]:
        m = self.m
        if module == "_base":
            return self._emit_base(module)
        body: List[str] = []
        classes = sorted(
            (c for c in m.classes.values() if c.module == module and c.kind != "variant"),
            key=lambda c: c.name,
        )
        for cm in classes:
            if cm.kind == KIND_COMPACT_NODE:
                body.extend(self.emit_compact_node(cm, module))
                continue
            body.extend(self.emit_interface(cm, module))
            body.extend(self.emit_loader(cm, module))
        if module in ("_expr", "_stmt"):
            root = "Expr" if module == "_expr" else "Stmt"
            for tag in m.enums[root].variants:
                cm = m.variants[f"{root}::{tag}"]
                if cm.module != module:
                    continue
                body.extend(self.emit_interface(cm, module))
                body.extend(self.emit_loader(cm, module))
            body.extend(self.emit_hierarchy(root, module))
        if module == "_types":
            body.extend(self.emit_type_hierarchy(module))
        if module == "_module":
            # `Module` itself is in the loop above; only the two JSON-string
            # entry points are left, and they are hand-written public API.
            for line in narrative.TS_MODULE_EXTRAS["parseModule"].rstrip().split("\n"):
                body.append(line)
            body.append("")
            for line in narrative.TS_MODULE_EXTRAS["parseProgram"].rstrip().split("\n"):
                body.append(line)
            body.append("")
        return body

    def _wire_type(self, f: FieldModel, module: str) -> str:
        """A `Pos` member as it arrives inside a `NodeRef`.

        Rust's `Node` declares these as plain `String`/`u64` and its
        hand-written `Serialize` always writes them, so the *decoded* type is
        exact. The wire type is not: a caller may hand `nodeFromWire` an object
        that was never produced by a parser -- a hand-built fixture, a partial
        tree from an older version -- and reading a missing key should give
        `undefined` rather than being a type error at the call site. So every
        key on a `WireNode` is optional even though none of them is optional in
        the struct. A bare `WirePos` has no payload to be missing alongside, so
        it keeps them required.
        """
        return f"{self.field_type(f, module, {})} | undefined"

    def _emit_base(self, module: str) -> List[str]:
        m = self.m
        node = m.classes["Node"]
        pos_fields = [f for f in node.fields if f.name not in ("node", "id")]
        body: List[str] = []
        body.append("// --- Pos " + "-" * 62)
        body.append("")
        body.extend(
            _jsdoc(
                "`ast::Pos` — a tuple struct, so its five members are inlined into every\n"
                "`NodeRef` on the wire rather than nested under a key of their own.\n"
                "They are the same five keys in `Node`, which is why `Node` and `Comment`\n"
                "extend `Partial<Pos>` instead of repeating the list."
            )
        )
        body.append("export interface Pos {")
        for f in pos_fields:
            body.append(f"  {naming.ts_field_name(f.name)}: {self.field_type(f, module, {})};")
        body.append("}")
        body.append("")
        body.append("// --- Node " + "-" * 61)
        body.append("")
        body.extend(
            _jsdoc(
                "`Node<T>` — the positional wrapper around any AST payload.\n\n"
                "Rust's `ast::Node<T>` has a hand-written `Serialize` impl, so its output\n"
                "keys come from that impl rather than from a derive. `id` is\n"
                "`skip_deserializing` and only appears when the AST-index serialiser is\n"
                "switched on, which is why it is optional and untyped: there is nothing to\n"
                "decode it as, and guessing would be worse than passing it through."
            )
        )
        body.append("export interface Node<T> extends Partial<Pos> {")
        body.append("  node: T;")
        for f in node.fields:
            if f.name == "id":
                body.append("  id?: unknown;")
        body.append("}")
        body.append("")
        for line in narrative.TS_MAYBE_NODE.rstrip().split("\n"):
            body.append(line)
        body.append("")
        body.append("// --- the wire shapes the helpers below take " + "-" * 27)
        body.append("")
        body.extend(
            _jsdoc(
                "`NodeRef<T>` as it arrives: the payload under `node`, and the five\n"
                "position members beside it. Every key is optional because `NodeRef` is\n"
                "optional at *two* levels — the wrapper may be absent, and a wrapper that\n"
                "is present may still hold no value."
            )
        )
        body.append("interface WireNode<U> {")
        body.append("  node: U;")
        for f in node.fields:
            if f.name == "id":
                body.append("  id?: unknown;")
        for f in pos_fields:
            body.append(f"  {f.wire}?: {self._wire_type(f, module)};")
        body.append("}")
        body.append("")
        body.extend(
            _jsdoc(
                "The same five members without the payload, as a bare `Pos`. A `Pos` is a\n"
                "tuple struct with no `Option` in it, so on the wire all five are\n"
                "present together or the object is not a position at all -- unlike\n"
                "`WireNode`, where they sit beside a payload that may itself be missing."
            )
        )
        body.append("interface WirePos {")
        for f in pos_fields:
            body.append(f"  {f.wire}: {self.field_type(f, module, {})};")
        body.append("}")
        body.append("")
        body.extend(
            _jsdoc(
                "Lift the five position members off a wrapper. Exported because `Pos`\n"
                "is `ast.rs`'s own type and a caller holding a raw wire node should not have\n"
                "to name the keys."
            )
        )
        body.append("export function posFromWire(w: WirePos | undefined | null): Pos | undefined {")
        body.append("  if (!w) return undefined;")
        body.append("  return {")
        for f in pos_fields:
            body.append(f"    {naming.ts_field_name(f.name)}: w.{f.wire},")
        body.append("  };")
        body.append("}")
        body.append("")
        body.extend(
            _jsdoc(
                "Decode one `NodeRef<T>`, given the loader for its payload. This is the\n"
                "function every other decoder calls, and the reason a `NodeRef<T>` cannot\n"
                "be a type on its own: the payload is polymorphic and the wrapper is not."
            )
        )
        body.append("export function nodeFromWire<T, U>(")
        body.append("  w: WireNode<U> | undefined | null,")
        body.append("  load: (inner: U) => T,")
        body.append("): Node<T> | undefined {")
        body.append("  if (!w) return undefined;")
        body.append("  const inner = w.node !== undefined ? load(w.node) : (undefined as unknown as T);")
        body.append("  return {")
        body.append("    node: inner,")
        for f in node.fields:
            if f.name == "id":
                body.append("    id: w.id,")
        for f in pos_fields:
            body.append(f"    {naming.ts_field_name(f.name)}: w.{f.wire},")
        body.append("  };")
        body.append("}")
        body.append("")
        for line in narrative.TS_MAP_NODES.rstrip().split("\n"):
            body.append(line)
        body.append("")
        comment = m.classes["Comment"]
        body.extend(self.emit_interface(comment, module))
        body.extend(self._comment_loader(comment, {}, module))
        return body

