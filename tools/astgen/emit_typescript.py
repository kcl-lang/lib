    def emit_hierarchy(self, root: str, module: str) -> List[str]:
        """The variant interfaces, the tag table and the polymorphic loader."""
        m = self.m
        root_cm = m.enums[root]
        entries = [(tag, m.variants[f"{root}::{tag}"]) for tag in root_cm.variants]
        needs: Dict[str, Set[str]] = {}
        out: List[str] = []
        for _, cm in entries:
            # A variant whose payload is also held untagged somewhere -- `Target`
            # in an assignment target, `Check` in a schema body -- has its
            # interface in the DTO module that owns it. Emitting it here as well
            # would be a duplicate declaration of the same name.
            if cm.module == module:
                out.extend(self.emit_interface(cm, module))
        out.extend(_jsdoc(narrative.TS_DISPATCH_NOTE.format(root=root)))
        out.append(
            "let REGISTRY: Record<string, (w: Record<string, unknown>) => unknown> | undefined;"
        )
        out.append("")
        out.append("function tagLoaders(): Record<string, (w: Record<string, unknown>) => unknown> {")
        out.append("  if (!REGISTRY) {")
        out.append("    REGISTRY = {")
        for tag, cm in entries:
            fn = self.loader_name(cm.rust_name)
            out.append(f"      {tag}: {self.ref(fn, module, needs)},")
        out.append("    };")
        out.append("  }")
        out.append("  return REGISTRY;")
        out.append("}")
        self._merge_imports(module, needs)
        out.append("")
        scope = root.lower()
        out.extend(
            _jsdoc(
                f"Polymorphic `{root}` loader. Returns `undefined` for a payload with no\n"
                "`type`.\n\n"
                "Typed `unknown` on purpose: the alternative is a discriminated union of\n"
                f"every {root} interface, which is a different package from the one the\n"
                "contract test exercises, and the test is about the wire shape."
            )
        )
        out.append(
            f"export function {scope}FromWire(w: Record<string, unknown> | undefined | null): unknown {{"
        )
        out.append("  if (!w) return undefined;")
        out.append("  const variant = w.type as string | undefined;")
        out.append("  if (typeof variant !== 'string') return undefined;")
        out.append("  const loader = tagLoaders()[variant];")
        out.append("  if (loader) return Object.assign({ type: variant }, loader(w));")
        out.append("  // A tag this build does not know keeps its own shape rather than being")
        out.append("  // dropped: a newer parser's output degrades to a marked object instead")
        out.append("  // of vanishing.")
        out.append("  return { type: variant, unknown: true };")
        out.append("}")
        out.append("")
        return out

    def emit_type_hierarchy(self, module: str) -> List[str]:
        """`Type` -- the one adjacently tagged hierarchy, so a `switch`.

        There is no registry to build here: an adjacently tagged variant's
        payload is under a content key, and the four variants that have one
        read a different shape from it -- a bare string (`Basic`), the payload
        struct itself (`List`), a second tagged document (`Literal`), a bare
        `Identifier` (`Named`).
        """
        m = self.m
        root_cm = m.enums["Type"]
        out: List[str] = []
        for tag in root_cm.variants:
            cm = m.variants[f"Type::{tag}"]
            out.extend(self.emit_interface(cm, module))
        out.extend(_jsdoc(
            "`Type` is `tag`/`content`, so the tag names the *shape* and not the type:\n"
            "`Basic` carries the bare string `\"Int\"` and never `{\"type\": \"Int\"}`.\n"
            "Keying a registry on `\"Int\"` yields nothing, which is the whole reason\n"
            "this hierarchy is a `switch` over the eight declared variants."
        ))
        out.append("export type Type =")
        names = [m.variants[f"Type::{t}"].name for t in root_cm.variants] + ["UnknownType"]
        for i, n in enumerate(names):
            out.append(f"  | {n}" + (";" if i == len(names) - 1 else ""))
        out.append("")
        out.extend(unknown_type())
        out.extend(_jsdoc(
            "Polymorphic `Type` loader. Returns `undefined` for a payload with no\n"
            "`type`."
        ))
        out.append(
            "export function typeFromWire(w: Record<string, unknown> | undefined | null): Type | undefined {"
        )
        out.append("  if (!w) return undefined;")
        out.append("  const tag = w.type as string | undefined;")
        out.append("  if (typeof tag !== 'string') return undefined;")
        out.append("  const value = w.value;")
        out.append("  switch (tag) {")
        for tag in root_cm.variants:
            out.extend(self._type_arm(tag, m.variants[f"Type::{tag}"], module))
        for line in narrative.TS_TYPE_FALLBACK.rstrip("\n").split("\n"):
            out.append("    " + ("  " + line if line.startswith("return") else line))
        out.append("  }")
        out.append("}")
        out.append("")
        return out

    def _type_arm(self, tag: str, cm: ClassModel, module: str) -> List[str]:
        needs: Dict[str, Set[str]] = {}
        out: List[str] = []
        # A variant whose single field *is* the content document reads the
        # content directly; one that inlines a payload struct's own fields
        # binds it first.
        if not cm.fields:
            # A unit variant: the tag is the whole document, so there is no
            # content key to descend through and no payload to bind.
            out.append(f"    case '{tag}':")
            out.append(f"      return {{ type: '{tag}' }};")
            return out
        inline = all(f.inline for f in cm.fields)
        if inline:
            out.append(f"    case '{tag}':")
            src = "value"
        else:
            out.append(f"    case '{tag}': {{")
            out.append("      const payload = (value || {}) as Record<string, unknown>;")
            src = "payload"
        out.append("      return {")
        out.append(f"        type: '{tag}',")
        for f in cm.fields:
            prop = naming.ts_field_name(f.name)
            value = (
                self.read_inline(f, src, module, needs) if inline else self.read(f, src, module, needs)
            )
            out.extend(self._property(prop, value, "        "))
        if cm.derived:
            attr, _ = cm.derived
            out.append(
                f"        {naming.ts_field_name(attr)}: {self.derived_read(cm, src, not inline)},"
            )
        out.append("      };")
        if not inline:
            out.append("    }")
        self._merge_imports(module, needs)
        return out

