    def class_doc(self, cm: ClassModel, flattened: bool = False) -> str:
        """The whole JSDoc block for a class, ready to emit verbatim.

        `narrative.TS_CLASS_DOCS` holds finished blocks for the classes whose
        subtlety is not visible from the Rust alone; everything else is derived
        here from the model's own answers.
        """
        override = narrative.TS_CLASS_DOCS.get(cm.name)
        if override:
            return override.strip("\n")
        if flattened:
            return (
                "The wrapper's position and the payload's own fields are *one*\n"
                "object, not a payload nested under `node`: the decoded value is\n"
                "both. `extends Partial<Pos>` says so in the type."
            )
        if cm.base in ("Expr", "Stmt") and cm.tag:
            head = (
                f"`{cm.base}::{cm.tag}` — `ast::{cm.rust_name}`, whose fields serde\n"
                "flattens into the tag's own object."
            )
            if cm.shared:
                head += (
                    "\n\nThe same struct is also reached untagged, through a field declared\n"
                    "with the struct rather than with the variant, so one decoder serves\n"
                    "both positions and only the tagged one gets a `type` key."
                )
            return head
        if cm.base == "Type":
            return (
                f"`{cm.base}::{cm.tag}` — the `value` side of the content key, with the\n"
                "tag the dispatcher reads beside it."
            )
        if cm.rust_doc:
            return cm.rust_doc.strip("\n")
        return f"`ast::{cm.rust_name}` — a plain struct; on the wire it has no `type` key."

    def field_note(self, cm: ClassModel, f: FieldModel) -> str:
        for key in (
            f"{cm.rust_name}.{f.name}",
            f"{cm.name}.{f.name}",
            f"{cm.name}.*",
        ):
            note = narrative.TS_FIELD_NOTES.get(key)
            if note:
                return note.strip("\n")
        return ""

