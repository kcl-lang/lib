def _docstring(text: str) -> List[str]:
    """Indent a class docstring to its body, closing the quotes on their own line.

    The prose in :mod:`astgen.narrative` is written flush-left because it is
    read there; here it is a method-level docstring and every line but the
    first has to carry the body's indentation or the file does not parse.
    """
    lines = text.strip("\n").split("\n")
    if len(lines) == 1:
        return [f'    """{lines[0]}"""']
    out = [f'    """{lines[0]}']
    out += [("    " + line).rstrip() for line in lines[1:]]
    out.append('    """')
    return out


def _py_type(f: FieldModel) -> str:
    if f.shape == SHAPE_STR:
        return "str"
    if f.shape == SHAPE_NUM:
        return "int"
    raise EmitError(f"Pos member {f.name} is a {f.shape}")


def _alias_note(cm: ClassModel) -> str:
    if not cm.aliases:
        return ""
    return "\n\n" + "\n".join(
        f"Aliased as ``{a}`` — {ALIAS_REASONS.get(a, 'an alias the public API already exposed')}."
        for a in cm.aliases
    )


def _rust_struct_doc(cm: ClassModel) -> str:
    if not cm.fields:
        return ""
    lines = ["Rust declares ``pub struct %s {``" % cm.rust_name]
    for f in cm.fields:
        lines.append(f"    pub {f.wire}: {f.rust_type},")
    lines.append("}``")
    return "\n".join(lines)


def _payload_note(tag: str, payload: str) -> str:
    return (
        f"the ``{tag}`` payload is a ``NodeRef<{payload}>``"
        if payload != "String"
        else f"the ``{tag}`` payload is a bare ``NodeRef<String>``, not an expression"
    )


def _op_doc(em: ClassModel) -> str:
    return (
        f"``ast::{em.name}`` — a fieldless enum, so every variant is a bare JSON\n"
        "string on the wire rather than an object."
    )
