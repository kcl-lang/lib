"""Emit the Python binding's ``kcl_lib/ast`` package from the model.

The class list, the field list, the annotations, the ``from_dict`` / ``to_dict``
bodies, the tag registries and the operator enumerations are all derived. What
the emitter adds is the binding's own conventions, which are not properties of
the Rust source:

* a **lazy import** per method rather than one per module, because the seven
  modules reference each other in a cycle and only the direction of the cycle
  is a local decision;
* the ``NodeRef[...]`` string annotations the existing API exposes;
* ``to_payload`` on the ``Type`` variants, which is the adjacent-tag payload
  dumper, against ``to_dict`` on the internally-tagged ``Expr``/``Stmt``
  variants whose fields sit in the tag's own object.

All three are *preserved on purpose*. The public API of this package is a
contract, and ``python/tests/ast_contract_test.py`` is its test.
"""

from __future__ import annotations

from typing import Dict, List, Optional, Set, Tuple

from . import naming, narrative
from .model import (
    AstModel,
    ClassModel,
    FieldModel,
    KIND_COMPACT_NODE,
    KIND_COMPACT_VALUE,
    SHAPE_BOOL,
    SHAPE_CLASS_REF,
    SHAPE_COMPACT_NODE,
    SHAPE_DOC,
    SHAPE_GENERIC,
    SHAPE_NODE,
    SHAPE_NODE_LIST,
    SHAPE_NODE_STR,
    SHAPE_NUM,
    SHAPE_OP,
    SHAPE_OPAQUE,
    SHAPE_OP_LIST,
    SHAPE_OPT_NODE_LIST,
    SHAPE_OPT_NUM,
    SHAPE_OPT_STR,
    SHAPE_OPT_VEC,
    SHAPE_RAW_LIST,
    SHAPE_STR,
    SHAPE_VALUE_LIST,
    SHAPE_VERBATIM,
)

HEADER = """# Code generated by tools/generate_ast.py from
# kcl-lang/kcl/crates/ast/src/ast.rs (sha256:{sha}).
# DO NOT EDIT BY HAND — run `python3 tools/generate_ast.py` and commit the
# result, or `ruby hack/check_generated_ast.rb` will fail.
#
# Every class, field, wire tag and operator below is derived from the Rust
# source. The prose is not; see tools/astgen/narrative.py.
"""

PY_MODULES = ["_base", "_op", "_dto", "_expr", "_stmt", "_types", "_module"]

ALIAS_REASONS = {
    "Decorator": "a decorator is a `CallExpr`, and Rust has no separate type for it",
    "SchemaConfig": "`UnificationStmt.value` is a `NodeRef<SchemaExpr>`",
    "KeyValuePair": "the `DictComp.entry` position has the same shape",
    "TargetExpr": "the `Expr::Target` variant is this same struct, with a tag",
    "IdentifierExpr": "the `Expr::Identifier` variant is this same struct, with a tag",
}


class EmitError(RuntimeError):
    pass


class PythonEmitter:
    def __init__(self, model: AstModel):
        self.m = model
        self.top_imports: Dict[str, Dict[str, Set[str]]] = {}
        #: Class *name* -> module. Needed because a variant class can be reached
        #: under either key (`Expr::Identifier` and `Identifier` are the same
        #: object) and the registry has to import it from wherever it lives.
        self.module_of: Dict[str, str] = {}
        for cm in list(model.classes.values()) + list(model.variants.values()):
            self.module_of.setdefault(cm.name, cm.module)

    # ------------------------------------------------------------------
    # symbol resolution
    # ------------------------------------------------------------------

    def loader(self, payload: Optional[str]) -> Optional[Tuple[str, str, str]]:
        """``(source, module, symbol)`` for a payload's decoder, or None."""
        if payload is None or payload in naming.PRIMITIVE_PAYLOADS:
            return None
        em = self.m.enums.get(payload)
        if em is not None and em.kind == "op_enum":
            # A fieldless enum is a bare JSON string on the wire, so there is
            # nothing to decode: the raw value *is* the value.
            return None
        for special, fn in (("Expr", "expr"), ("Stmt", "stmt"), ("Type", "type")):
            if payload == special:
                mod = {"expr": "_expr", "stmt": "_stmt", "type": "_types"}[fn]
                return (f"{fn}_from_dict", mod, f"{fn}_from_dict")
        cm = self.m.classes.get(payload)
        if cm is None:
            raise EmitError(f"no decoder for payload {payload}")
        return (f"{cm.name}.from_dict", cm.module, cm.name)

    def dumper(self, payload: Optional[str]) -> Optional[Tuple[str, str, str]]:
        if payload is None or payload in naming.PRIMITIVE_PAYLOADS:
            return None
        em = self.m.enums.get(payload)
        if em is not None and em.kind == "op_enum":
            return None
        for special, fn in (("Expr", "expr"), ("Stmt", "stmt"), ("Type", "type")):
            if payload == special:
                mod = {"expr": "_expr", "stmt": "_stmt", "type": "_types"}[fn]
                return (f"{fn}_to_dict", mod, f"{fn}_to_dict")
        cm = self.m.classes.get(payload)
        if cm is None:
            raise EmitError(f"no serializer for payload {payload}")
        return (f"{cm.name}.to_dict", cm.module, cm.name)

    # ------------------------------------------------------------------
    # field rendering
    # ------------------------------------------------------------------

    def annotation(self, f: FieldModel) -> str:
        s = f.shape
        if s in (SHAPE_STR, SHAPE_OP):
            return 'str = ""'
        if s == SHAPE_OPT_STR:
            return "Optional[str] = None"
        if s == SHAPE_NUM:
            return "int = 0"
        if s == SHAPE_OPT_NUM:
            return "Optional[int] = None"
        if s == SHAPE_BOOL:
            return "bool = False"
        if s in (SHAPE_VERBATIM, SHAPE_OPAQUE):
            return "Any = None"
        if s == SHAPE_DOC:
            return "dict = field(default_factory=dict)"
        if s in (SHAPE_NODE_STR, SHAPE_NODE, SHAPE_COMPACT_NODE):
            return "Optional[Node] = None"
        if s == SHAPE_NODE_LIST:
            return "List[Node] = field(default_factory=list)"
        if s == SHAPE_OPT_VEC:
            # `Option<Vec<T>>`: two states on the wire, so `None` and a list.
            # Not `[]` -- an empty `params_ty` is a different function from a
            # missing one, and defaulting it away loses which one this was.
            return "Optional[List[Node]] = None"
        if s == SHAPE_OPT_NODE_LIST:
            return "List[Optional[Node]] = field(default_factory=list)"
        if s in (SHAPE_RAW_LIST, SHAPE_OP_LIST):
            return "List[str] = field(default_factory=list)"
        if s == SHAPE_VALUE_LIST:
            name = self.m.classes[f.payload].name
            return f"List[{name}] = field(default_factory=list)"
        if s == SHAPE_CLASS_REF:
            name = self.m.classes[f.payload].name
            return f"Optional[{name}] = None"
        if s == SHAPE_GENERIC:
            return "Optional[T] = None"
        raise EmitError(f"no annotation for shape {s} ({f.name})")

    def _read(self, f: FieldModel, needs: Dict[str, Set[str]], prelude: List[str]) -> str:
        s = f.shape
        # An inline field *is* the content document: the dispatcher has already
        # lifted it out from under `"value"`, so there is no key left to read.
        # `Type::Basic`'s payload is the bare string `"Int"` and
        # `Type::Named`'s is the `Identifier` object, and looking for a `"value"`
        # key inside either of them finds nothing -- which is how a whole type
        # tree decodes to empty objects without raising.
        get = "d" if f.inline else f'd.get("{f.wire}")'
        ld = self.loader(f.payload)
        if ld:
            needs.setdefault(ld[1], set()).add(ld[2])
        arg = f", {ld[0]}" if ld else ""
        if s in (SHAPE_STR, SHAPE_OP):
            return f'{get} or ""'
        if s in (SHAPE_OPT_STR, SHAPE_OPT_NUM, SHAPE_VERBATIM, SHAPE_GENERIC, SHAPE_OPAQUE):
            return get
        if s == SHAPE_NUM:
            return f"int({get} or 0)"
        if s == SHAPE_BOOL:
            # `bool` is `skip_serializing_if = "is_false"`, so the key is absent
            # rather than `false` when the answer is no. `bool(x or False)` is
            # the only spelling that reads `False` for both.
            return f"bool({get} or False)"
        if s == SHAPE_NODE_STR:
            needs.setdefault("_base", set()).add("node_from_dict")
            return f"node_from_dict({get})"
        if s in (SHAPE_NODE, SHAPE_COMPACT_NODE):
            needs.setdefault("_base", set()).add("node_from_dict")
            return f"node_from_dict({get}{arg})"
        if s in (SHAPE_NODE_LIST,):
            needs.setdefault("_base", set()).add("node_list_from_dict")
            return f"node_list_from_dict({get}{arg})"
        if s == SHAPE_OPT_VEC:
            needs.setdefault("_base", set()).add("node_list_from_dict")
            var = f"raw_{f.wire}"
            prelude.append(f"        {var} = {get}")
            # `None` stays `None`. The reader treats a missing list and an empty
            # one the same way because the parser never produces `Some(vec![])`
            # -- `crates/parser/src/parser/ty.rs` turns an empty `params_type`
            # into `None` -- so an empty list here would be a distinction the
            # wire does not carry.
            return (
                f"None\n            if {var} is None\n            else "
                f"node_list_from_dict({var}{arg})"
            )
        if s == SHAPE_OPT_NODE_LIST:
            needs.setdefault("_base", set()).add("optional_node_list_from_dict")
            return f"optional_node_list_from_dict({get}{arg})"
        if s in (SHAPE_RAW_LIST, SHAPE_OP_LIST):
            var = f"raw_{f.wire}"
            prelude.append(f"        {var} = {get}")
            return f"list({var}) if isinstance({var}, list) else []"
        if s == SHAPE_VALUE_LIST:
            name = self.m.classes[f.payload].name
            needs.setdefault(self.m.classes[f.payload].module, set()).add(name)
            var = f"raw_{f.wire}"
            prelude.append(f"        {var} = {get}")
            return f"[{name}.from_dict(p) for p in {var}] if isinstance({var}, list) else []"
        if s == SHAPE_CLASS_REF:
            name = self.m.classes[f.payload].name
            needs.setdefault(self.m.classes[f.payload].module, set()).add(name)
            return f"{name}.from_dict({get}) if isinstance({get}, dict) else None"
        if s == SHAPE_DOC:
            var = f"raw_{f.wire}"
            prelude.append(f"        {var} = {get}")
            return f"dict({var}) if isinstance({var}, dict) else {{}}"
        raise EmitError(f"no reader for shape {s} ({f.name})")

    def _write(self, f: FieldModel, needs: Dict[str, Set[str]]) -> str:
        s = f.shape
        attr = f"self.{f.name}"
        dp = self.dumper(f.payload)
        if dp:
            needs.setdefault(dp[1], set()).add(dp[2])
        arg = f", {dp[0]}" if dp else ""
        if s == SHAPE_NODE_STR:
            needs.setdefault("_base", set()).add("node_to_dict")
            return f"node_to_dict({attr})"
        if s in (SHAPE_NODE, SHAPE_COMPACT_NODE):
            needs.setdefault("_base", set()).add("node_to_dict")
            return f"node_to_dict({attr}{arg})"
        if s in (SHAPE_NODE_LIST,):
            needs.setdefault("_base", set()).add("node_list_to_dict")
            return f"node_list_to_dict({attr}{arg})"
        if s == SHAPE_OPT_VEC:
            needs.setdefault("_base", set()).add("node_list_to_dict")
            return f"None if {attr} is None else node_list_to_dict({attr}{arg})"
        if s == SHAPE_OPT_NODE_LIST:
            needs.setdefault("_base", set()).add("optional_node_list_to_dict")
            return f"optional_node_list_to_dict({attr}{arg})"
        if s == SHAPE_VALUE_LIST:
            return f"[x.to_dict() for x in {attr}]"
        if s in (SHAPE_RAW_LIST, SHAPE_OP_LIST):
            return f"[str(x) for x in {attr}]"
        if s == SHAPE_CLASS_REF:
            # An inline class-ref payload is `None` when the document did not
            # carry one, and `None` has to survive the round trip rather than
            # being turned into an empty object.
            return f"{attr}.to_dict() if {attr} is not None else None"
        return attr

    # ------------------------------------------------------------------
    # classes
    # ------------------------------------------------------------------

    def class_doc(self, cm: ClassModel) -> str:
        if cm.kind in ("variant", "shared"):
            return self._variant_doc(cm)
        if cm.kind in (KIND_COMPACT_NODE, KIND_COMPACT_VALUE):
            return (narrative.CLASS_DOCS.get(cm.name) or _rust_struct_doc(cm) or "") + _alias_note(cm)
        doc = narrative.CLASS_DOCS.get(cm.name)
        if doc is None:
            doc = _rust_struct_doc(cm) or f"``ast::{cm.rust_name}``."
        return doc + _alias_note(cm)

    def _variant_doc(self, cm: ClassModel) -> str:
        internal = cm.base in ("Expr", "Stmt")
        base = f"``{cm.base}::{cm.tag}``."
        if internal:
            base += (
                "\n\nInternally tagged with **no** ``rename_all``, so the wire tag is\n"
                "the variant name verbatim and the struct's fields are *flattened into\n"
                "the same object as the tag*. There is no wrapper key to descend\n"
                "through."
            )
        else:
            base += (
                "\n\n``Type`` is adjacently tagged (``tag = \"type\", content =\n"
                '"value"``), so the tag names the *shape* and the payload lives under\n'
                "``value`` -- and a newtype payload is inlined there, with no extra\n"
                "wrapper key."
            )
        if cm.shared:
            base += (
                f"\n\nThe payload is ``ast::{cm.rust_name}``, a plain struct shared with the\n"
                "untagged positions that reach it through a field declared with the\n"
                'struct rather than with the variant, so the same object arrives here as\n'
                '``{"type":"%s", ...fields}`` and there as ``{...fields}``.'
                % (cm.tag or "")
            )
        elif cm.fields and cm.rust_name not in _NAMELESS_PAYLOADS:
            base += "\n\n" + _rust_struct_doc(cm)
        return base + _alias_note(cm)

    def emit_class(self, cm: ClassModel) -> List[str]:
        out: List[str] = []
        from_needs: Dict[str, Set[str]] = {}
        to_needs: Dict[str, Set[str]] = {}
        prelude: List[str] = []
        reads = [f"{f.name}={self._read(f, from_needs, prelude)}" for f in cm.fields]
        writes = [f'"{f.wire}": {self._write(f, to_needs)}' for f in cm.fields]

        is_comment = cm.rust_name == "Comment"
        base = f"({cm.base})" if cm.base else ""
        out.append("@dataclass")
        out.append(f"class {cm.name}{base}:")
        out.extend(_docstring(self.class_doc(cm)))
        out.append("")
        if cm.fields:
            for f in cm.fields:
                out.append(f"    {f.name}: {self.annotation(f)}")
        else:
            out.append("    pass")
        out.append("")
        out.append("    @classmethod")
        if is_comment:
            out.append('    def from_dict(cls, d: Optional[dict]) -> Optional["Comment"]:')
        else:
            out.append(f'    def from_dict(cls, d: Any) -> "{cm.name}":')
        out.extend(self._lazy_imports(from_needs, cm.module))
        if is_comment:
            out.append("        # `d` is the payload, not the wrapper: `Module.comments` passes")
            out.append("        # this in as the `NodeRef` loader and `Node.from_dict` has already")
            out.append("        # lifted the key out before handing it over. Unwrapping a second")
            out.append("        # time here reads a key that is not on the payload and falls")
            out.append('        # through to `""` for every comment in the file.')
        # A class whose every field is inline receives the *content* document,
        # and that document is not always a dict: `Type::Basic`'s payload is the
        # bare string `"Int"`. Coercing it to `{}` first would empty the field.
        if not (cm.fields and all(f.inline for f in cm.fields)):
            out.append("        d = d if isinstance(d, dict) else {}")
        if cm.kind == KIND_COMPACT_NODE and cm.payload_loaders:
            out.append('        kind = d.get("%s") or ""' % (cm.tag or "type"))
            first, rest = cm.variants[0], cm.variants[1:]
            out.append(f'        if kind == "{first}":')
            out.append("            # " + _payload_note(first, cm.payload_loaders[first]))
            out.extend(self._compact_node_read(first, cm, from_needs))
            for tag in rest:
                out.append("        else:")
                out.append("            # " + _payload_note(tag, cm.payload_loaders[tag]))
                out.extend(self._compact_node_read(tag, cm, from_needs))
            out.append(f"        return cls({cm.fields[0].name}=kind, {cm.fields[1].name}=node)")
            out.append("")
        else:
            out.extend(prelude)
            if reads:
                out.append("        return cls(")
                out.extend(f"            {r}," for r in reads)
                out.append("        )")
            else:
                out.append("        return cls()")
            out.append("")

        if cm.base == "Type" and not writes:
            # A unit variant of an adjacently tagged enum: serde writes the bare
            # tag and *no* content key at all. `to_payload` is therefore absent,
            # which is what `type_to_dict` tests for -- emitting
            # `{"type": "Any", "value": {}}` would not survive a strict reader.
            pass
        elif cm.base == "Type":
            out.append("    def to_payload(self) -> Any:")
            out.extend(self._lazy_imports(to_needs, cm.module))
            if len(cm.fields) == 1 and cm.fields[0].inline:
                # The field *is* the content: `Type::Basic`'s payload is the bare
                # string `"Int"` and `Type::Named`'s is the `Identifier` object,
                # so the payload is that value rather than a dict keyed by it.
                out.append(f"        return {self._write(cm.fields[0], to_needs)}")
            else:
                out.append("        return {")
                out.extend(f"            {w}," for w in writes)
                out.append("        }")
            out.append("")
            out.append("    # `to_payload` is what `type_to_dict` calls: the tag is written")
            out.append("    # *beside* this document, not inside it. `Expr` and `Stmt` variants")
            out.append("    # use `to_dict` instead because their fields sit in the tag's own")
            out.append("    # object.")
            out.append("    to_dict = to_payload")
            out.append("")
        elif cm.kind == KIND_COMPACT_NODE:
            out.append("    def to_dict(self) -> dict:")
            out.extend(self._lazy_imports(to_needs, cm.module))
            first, rest = cm.variants[0], cm.variants[1:]
            # The payload's decoder differs per tag, so its *encoder* does too:
            # `Member` holds a bare string and `Index` an `Expr`, and handing
            # the raw dataclass to the wrong one leaves an object in the JSON.
            for i, tag in enumerate(cm.variants):
                out.append(f'        {"if" if i == 0 else "elif"} self.{cm.fields[0].name} == "{tag}":')
                out.append("        # " + _payload_note(tag, cm.payload_loaders[tag]))
                out.extend(self._compact_node_write(tag, cm, to_needs))
            out.append("        else:")
            out.append("        # " + _payload_note(first, cm.payload_loaders[first]))
            out.extend(self._compact_node_write(first, cm, to_needs))
            out.append("")
        else:
            out.append("    def to_dict(self) -> dict:")
            out.extend(self._lazy_imports(to_needs, cm.module))
            skipped = [f for f in cm.fields if f.skip_false]
            if cm.kind == "variant" and cm.base in ("Expr", "Stmt"):
                out.append("        out = {")
                out.extend(f"            {w}," for w in writes)
                out.append("        }")
                if skipped:
                    out.extend(self._skip_false(skipped))
                out.append("        # The tag goes back on under its own key, because the")
                out.append("        # variant's fields were flattened into this same object.")
                out.append('        out["type"] = "%s"' % (cm.tag or ""))
                out.append("        return out")
            elif writes:
                if skipped:
                    out.append("        out = {")
                    out.extend(f"            {w}," for w in writes)
                    out.append("        }")
                    out.extend(self._skip_false(skipped))
                    out.append("        return out")
                else:
                    out.append("        return {")
                    out.extend(f"            {w}," for w in writes)
                    out.append("        }")
            else:
                out.append("        return {}")
            out.append("")

        extra = narrative.EXTRA_METHODS.get(cm.name)
        if extra:
            out.append(extra.strip("\n"))
            out.append("")
        if cm.derived:
            out.extend(self._derived_property(*cm.derived))
            out.append("")
        return out

    def _derived_property(self, attr: str, source: str) -> List[str]:
        return [
            "    @property",
            f"    def {attr}(self) -> str:",
            f'        """The tag *inside* ``self.{source}``."""',
            f'        return self.{source}.get("{narrative.INNER_TAG_KEY}", "")',
        ]

    def _compact_node_read(self, tag: str, cm: ClassModel, needs: Dict[str, Set[str]]) -> List[str]:
        payload = cm.payload_loaders[tag]
        ld = self.loader(payload)
        if ld:
            needs.setdefault(ld[1], set()).add(ld[2])
        needs.setdefault("_base", set()).add("node_from_dict")
        arg = f", {ld[0]}" if ld else ""
        return [f'            node = node_from_dict(d.get("{cm.content or "value"}"){arg})']

    def _compact_node_write(self, tag: str, cm: ClassModel, needs: Dict[str, Set[str]]) -> List[str]:
        node_field = cm.fields[1]
        dp = self.dumper(node_field.payload) or self.dumper(cm.payload_loaders[tag])
        if dp:
            needs.setdefault(dp[1], set()).add(dp[2])
        needs.setdefault("_base", set()).add("node_to_dict")
        arg = f", {dp[0]}" if dp else ""
        tag_field = cm.fields[0]
        return [
            f'            return {{"type": self.{tag_field.name} or "{tag}", '
            f'"value": node_to_dict(self.{node_field.name}{arg})}}'
        ]

    def _skip_false(self, fields: List[FieldModel]) -> List[str]:
        out: List[str] = []
        for f in fields:
            out.append(f"        if not self.{f.name}:")
            out.append(f'            # `skip_serializing_if = "is_false"`: the key is absent,')
            out.append(f"            # not `false`, so writing one back would add a key the")
            out.append(f"            # parser never emitted and the round trip would not")
            out.append(f'            # be a fixed point.')
            out.append(f'            out.pop("{f.wire}", None)')
        return out

    def _lazy_imports(self, needs: Dict[str, Set[str]], module: str) -> List[str]:
        lines: List[str] = []
        for mod in naming.PY_MODULE_POLICY[module]["lazy"]:
            symbols = sorted(needs.get(mod, ()))
            if symbols:
                lines.append(f"        from .{mod} import {', '.join(symbols)}")
        return lines + [""] if lines else []

    # ------------------------------------------------------------------
    # Node / Pos
    # ------------------------------------------------------------------

    def emit_node(self) -> List[str]:
        node = self.m.classes["Node"]
        # `Pos` is a tuple struct in Rust; its five members are exactly `Node`'s
        # own fields minus the payload and the id, in declaration order, which is
        # the order `ast::PosTuple = (String, u64, u64, u64, u64)` also gives.
        pos_fields = [f for f in node.fields if f.name not in ("node", "id")]
        id_field = next(f for f in node.fields if f.name == "id")
        out: List[str] = []
        out.append("")
        out.append("# --- Pos " + "-" * 62)
        out.append("")
        out.append("@dataclass")
        out.append("class Pos:")
        out.append('    """Source position tuple (filename, line, column, end_line,')
        out.append("    end_column) -- ``ast::Pos``.")
        out.append("")
        out.append("    Every member is optional here because the wrapper it is inlined into")
        out.append("    carries a value on the wire, not a ``Pos`` document of its own.")
        out.append('    """')
        out.append("")
        for f in pos_fields:
            out.append(f"    {f.name}: Optional[{_py_type(f)}] = None")
        out.append("")
        out.append("    @classmethod")
        out.append('    def from_dict(cls, d: Optional[dict]) -> Optional["Pos"]:')
        out.append("        if d is None:")
        out.append("            return None")
        out.append("        return cls(")
        for f in pos_fields:
            out.append(f'            {f.name}=d.get("{f.wire}"),')
        out.append("        )")
        out.append("")
        out.append("    def to_dict(self) -> dict:")
        out.append("        d: dict = {}")
        for f in pos_fields:
            out.append(f'        if self.{f.name} is not None:')
            out.append(f'            d["{f.wire}"] = self.{f.name}')
        out.append("        return d")
        out.append("")
        out.append("")
        out.append("# --- Node " + "-" * 61)
        out.append("")
        out.append("@dataclass")
        out.append("class Node(Generic[T]):")
        out.append('    """``Node<T>`` — the positional wrapper around any AST payload.')
        out.append("")
        out.append("    Rust's ``ast::Node<T>`` has a hand-written ``Serialize`` impl, so its")
        out.append("    output keys come from that impl rather than from a derive: ``node``,")
        out.append("    the five position members, and ``id`` only when the AST-index")
        out.append("    serialiser has been switched on. ``id`` is ``skip_deserializing``, so a")
        out.append("    wrapper is read back with it when it is there and without it when it")
        out.append("    is not — a round trip through either direction loses nothing.")
        out.append('    """')
        out.append("")
        out.append("    node: Optional[T] = None")
        out.append(f"    {id_field.name}: Optional[Any] = None")
        out.append("    pos: Optional[Pos] = None")
        out.append("")
        out.append("    @classmethod")
        out.append('    def from_dict(cls, d: Optional[dict], inner_loader=None) -> Optional["Node[T]"]:')
        out.append('        """Deserialize a Node. ``inner_loader(node_dict) -> T`` resolves the')
        out.append("        polymorphic payload (e.g. ``expr_from_dict``).\"\"\"")
        out.append("        if d is None:")
        out.append("            return None")
        out.append('        inner = d.get("node")')
        out.append("        if inner_loader is not None:")
        out.append("            payload = inner_loader(inner)")
        out.append("        else:")
        out.append("            payload = inner")
        out.append("        return cls(")
        out.append("            node=payload,")
        out.append(f'            {id_field.name}=d.get("{id_field.wire}"),')
        out.append("            pos=Pos.from_dict(")
        out.append('                {k: v for k, v in d.items() if k != "node" and k != "id"}')
        out.append("            ),")
        out.append("        )")
        out.append("")
        out.append("    def to_dict(self, inner_dumper=None) -> dict:")
        out.append('        """Serialize. ``inner_dumper(node) -> dict`` turns ``self.node``')
        out.append("        into its dict representation. The ``pos`` fields are flattened")
        out.append("        alongside ``node`` and ``id`` to match the wire shape.\"\"\"")
        out.append("        if inner_dumper is not None and self.node is not None:")
        out.append("            inner = inner_dumper(self.node)")
        out.append("        else:")
        out.append("            inner = self.node")
        out.append('        d: dict = {"node": inner}')
        out.append(f"        if self.{id_field.name} is not None:")
        out.append(f'            d["{id_field.wire}"] = self.{id_field.name}')
        out.append("        if self.pos is not None:")
        out.append("            d.update(self.pos.to_dict())")
        out.append("        return d")
        return out

