    def emit_module(self, module: str) -> str:
        m = self.m
        classes = sorted(
            (c for c in m.classes.values() if c.module == module and c.kind != "variant"),
            key=lambda c: c.name,
        )
        variants = sorted(
            (m.variants[k] for k in m.variants if m.variants[k].module == module),
            key=lambda c: (c.base or "", c.tag or "", c.name),
        )
        head_needs = self._module_needs(classes, variants)
        self.top_imports[module] = head_needs

        roots = [r for r in m.roots if m.enums[r].module == module]
        # Everything is emitted as a list of lines joined by newlines, so the
        # blank-line convention has to be written out: each block below ends
        # with one empty line and each block starts with another, which is the
        # two blank lines PEP 8 asks for between top-level definitions.
        body: List[str] = [""]
        # The base class has to exist before anything that subclasses it, and a
        # hierarchy's own classes live in the same module as its base.
        for root in roots:
            body.append(narrative.HIERARCHY_BASE[root].strip("\n"))
            body.append("")
            body.append(narrative.UNKNOWN_CLASS[root].strip("\n"))
            body.append("")
        if module == "_base":
            body.extend(self.emit_node())
            body.append(narrative.NODE_REF_HELPERS.rstrip("\n"))
            body.append("")
        if module == "_op":
            for name in sorted(m.enums):
                em = m.enums[name]
                if em.kind != "op_enum" or em.module != module:
                    continue
                if name in narrative.OP_ENUM_EXCLUDE:
                    continue
                body.extend(self._op_class(em))
                body.append("")
        if module == "_expr":
            body.append(narrative.EXPR_CONTEXT_CLASS.rstrip("\n"))
            body.append("")
        for cm in classes:
            if module == "_base" and cm.name in ("Node",):
                continue
            body.append(f"# --- {cm.name} " + "-" * max(0, 66 - len(cm.name)))
            body.append("")
            body.extend(self.emit_class(cm))
            body.extend(self._aliases(cm))
            body.append("")
        for root in roots:
            for cm in variants:
                if cm.base != root:
                    continue
                body.append(f"# --- {cm.name} " + "-" * max(0, 66 - len(cm.name)))
                body.append("")
                body.extend(self.emit_class(cm))
                body.extend(self._aliases(cm))
                body.append("")
            self._emit_dispatch(root, body)
        if module == "_base":
            body.append(narrative.PARSE_ENTRY_POINTS.rstrip("\n"))
            body.append("")

        text = HEADER.format(sha=m.source_sha[:16])
        text += f'"""{narrative.MODULE_DOCS[module]}"""\n'
        text += self._module_head(module, head_needs)
        text += "\n".join(body).rstrip("\n") + "\n"
        text += self._module_footer(module)
        return text

    def _aliases(self, cm: ClassModel) -> List[str]:
        """The names this class is also exported under.

        They are assignments rather than subclasses so that ``isinstance`` and
        the module namespace both keep working: ``Decorator`` and ``CallExpr``
        are the same document, and a subclass would make them different ones.
        """
        if not cm.aliases:
            return []
        return [
            "",
            f"# {cm.name} under the name{'s' if len(cm.aliases) > 1 else ''} the",
            "# Java binding gives the same document. An assignment, not a",
            "# subclass: a decorator is a call, not a kind of call.",
            "",
        ] + [f"{a} = {cm.name}" for a in cm.aliases]

    def _op_class(self, em: ClassModel) -> List[str]:
        out = ["", f"class {em.name}(str, Enum):"]
        out.append(f'    """{narrative.CLASS_DOCS.get(em.name) or _op_doc(em)}"""')
        out.append("")
        for v in em.variants:
            out.append(f'    {v} = "{v}"')
        return out

    def _emit_dispatch(self, root: str, body: List[str]) -> None:
        """The registry, the polymorphic loader and its mirror.

        The two hierarchies differ in exactly one place, and it is the reason
        the whole generator exists: an internally tagged variant reads the
        *same object* as the tag (its struct fields were flattened into it),
        while an adjacently tagged variant reads that object's content key.
        """
        m = self.m
        root_cm = m.enums[root]
        entries = [(tag, m.variants[f"{root}::{tag}"]) for tag in root_cm.variants]
        registry = "\n".join(f'            "{tag}": {cm.name},' for tag, cm in entries) + "\n"
        # Any variant class that does not live in this module has to be pulled
        # in here, and inside the function is the only place that is not a cycle.
        foreign = sorted({cm.name for _, cm in entries if cm.module != root_cm.module})
        imports = ""
        if foreign:
            by_mod: Dict[str, List[str]] = {}
            for name in foreign:
                by_mod.setdefault(self.module_of[name], []).append(name)
            for mod in sorted(by_mod):
                imports += f"        from .{mod} import {', '.join(sorted(by_mod[mod]))}\n"
        adjacent = root_cm.content is not None
        body.append(
            narrative.DISPATCH_TEMPLATE.format(
                SCOPE=root.upper(),
                Root=root,
                root=root,
                scope=root.lower(),
                tag=root_cm.tag,
                registry=registry,
                imports=imports,
                value_arg=f'd.get("{root_cm.content}")' if adjacent else "d",
                emit=narrative.DISPATCH_EMIT_ADJACENT
                if adjacent
                else narrative.DISPATCH_EMIT_INTERNAL,
            ).rstrip("\n")
        )
        body.append("")

    def _module_needs(self, classes, variants) -> Dict[str, Set[str]]:
        needs: Dict[str, Set[str]] = {}
        for cm in list(classes) + list(variants):
            # A variant class subclasses its hierarchy's base, which has to be
            # in scope before the `class` statement is evaluated -- and for a
            # shared payload in `_dto` that base comes from `_expr` or `_stmt`.
            if cm.base:
                base_mod = {"Expr": "_expr", "Stmt": "_stmt", "Type": "_types"}[cm.base]
                if base_mod == cm.module:
                    needs.setdefault(base_mod, set()).add(cm.base)
                else:
                    needs.setdefault(base_mod, set()).add(cm.base)
            prelude: List[str] = []
            for f in cm.fields:
                self._read(f, needs, prelude)
            for f in cm.fields:
                self._write(f, needs)
        return needs

    def _module_head(self, module: str, needs: Dict[str, Set[str]]) -> str:
        lines = ["", "from __future__ import annotations", ""]
        if module == "_base":
            lines += [
                "import json",
                "from dataclasses import dataclass",
                "from typing import Any, Generic, List, Optional, TypeVar",
                "",
                'T = TypeVar("T")',
                "",
            ]
        elif module == "_op":
            lines += ["from enum import Enum", ""]
        else:
            lines += ["from dataclasses import dataclass, field", "from typing import Any, Dict, List, Optional", ""]
        if module == "_expr":
            # `ExprContext` is emitted into this module itself (see
            # narrative.EXPR_CONTEXT_CLASS), so nothing has to be imported for
            # it and `_op` does not declare it.
            pass
        for mod in naming.PY_MODULE_POLICY[module]["top"]:
            symbols = set(needs.get(mod, set()))
            if mod == "_base" and any(
                f.shape
                in (
                    SHAPE_NODE,
                    SHAPE_NODE_STR,
                    SHAPE_COMPACT_NODE,
                    SHAPE_NODE_LIST,
                    SHAPE_OPT_VEC,
                    SHAPE_OPT_NODE_LIST,
                )
                for c in self.m.classes.values()
                if c.module == module
                for f in c.fields
            ):
                symbols.add("Node")
            symbols.discard(module)
            if not symbols:
                continue
            ordered = [s for s in naming.PY_IMPORT_ORDER.get(mod, []) if s in symbols]
            ordered += sorted(s for s in symbols if s not in ordered)
            lines.append(f"from .{mod} import (")
            lines += [f"    {s}," for s in ordered]
            lines += [")", ""]
        return "\n".join(lines) + "\n"

    def _module_footer(self, module: str) -> str:
        exported = self._exports(module)
        if not exported:
            return ""
        out = ["", "__all__ = ["]
        out += [f'    "{e}",' for e in sorted(set(exported))]
        out.append("]")
        return "\n".join(out) + "\n"

    def _exports(self, module: str) -> List[str]:
        m = self.m
        if module == "_base":
            return [
                "Comment",
                "Node",
                "Pos",
                "node_from_dict",
                "node_list_from_dict",
                "node_to_dict",
                "optional_node_list_from_dict",
                "optional_node_list_to_dict",
                "parse_module",
                "parse_program",
            ]
        if module == "_op":
            return [
                m.enums[n].name
                for n in sorted(m.enums)
                if m.enums[n].kind == "op_enum"
                and m.enums[n].module == module
                and n not in narrative.OP_ENUM_EXCLUDE
            ]
        names = {
            c.name
            for c in m.classes.values()
            if c.module == module and c.kind != "variant"
        }
        names |= {
            c.name
            for c in m.variants.values()
            if c.module == module and c.base
        }
        names |= {a for c in m.classes.values() if c.module == module for a in c.aliases}
        if module in ("_expr", "_stmt", "_types"):
            root = {"_expr": "Expr", "_stmt": "Stmt", "_types": "Type"}[module]
            names |= {
                root,
                f"Unknown{root}",
                f"{root.lower()}_from_dict",
                f"{root.lower()}_to_dict",
            }
        if module == "_expr":
            names.add("ExprContext")
        if module == "_module":
            names |= {"Module"}
        return sorted(names)

    # ------------------------------------------------------------------
    # package __init__
    # ------------------------------------------------------------------

    def emit_package_init(self) -> str:
        m = self.m
        lines = [HEADER.format(sha=m.source_sha[:16]), '"""' + narrative.PACKAGE_DOC + '"""', ""]
        for module in PY_MODULES:
            names = self._exports(module)
            if not names:
                continue
            if len(names) == 1:
                lines.append(f"from .{module} import {names[0]}")
                continue
            lines.append(f"from .{module} import (")
            lines += [f"    {n}," for n in sorted(names)]
            lines.append(")")
        lines.append("")
        lines.append("__all__ = [")
        allnames: List[str] = []
        for module in PY_MODULES:
            allnames += self._exports(module)
        lines += [f'    "{n}",' for n in sorted(set(allnames))]
        lines.append("]")
        return "\n".join(lines) + "\n"


